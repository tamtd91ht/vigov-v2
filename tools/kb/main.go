const header = "Code generated by tools/kb. DO NOT EDIT — run `make kb` to regenerate."

type serviceEntry struct {
	Name    string `json:"name"`
	Path    string `json:"path"`
	HasMain bool   `json:"has_main"`
	Summary string `json:"summary"`
}

type symbolEntry struct {
	Kind string `json:"kind"`
	At   string `json:"at"`
}

func main() {
	root, err := findRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}

	services, err := scanServices(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}
	symbols, err := scanSymbols(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}

	out := filepath.Join(root, "kb", "30-indexes")
	write(out, "services.json", map[string]any{
		"_": header,
		"_description": "Every service, its path, and the one-line summary from its README. " +
			"Reasons for the boundaries live in kb/00-foundation/domain-boundaries.md.",
		"services": services,
	})
	write(out, "code-map.json", map[string]any{
		"_":            header,
		"_description": "Exported symbol -> file:line. USE THIS INSTEAD OF GREPPING THE REPO.",
		"symbols":      symbols,
	})

	// data-ownership is GENERATED FROM THE `-- @entity:` MARKS since 2026-09-20. It used to be
	// a placeholder reading "no schemas defined yet", and that sentence had been false since
	// ADR 0021 put the marks into the migrations — 24 marks across 7 services while the index
	// said none. The placeholder did not look broken, it looked like an early repo, so nobody
	// asked; and CLAUDE.md step 4 sends every session here FIRST, told not to read schemas.
	// A generated index that is empty for a stale reason is the quietest way to lose a rule.
	soHuuBang, canhBaoSoHuu, err := quetSoHuu(root, services)
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}
	canhBaoSoHuu = append(canhBaoSoHuu, trung(soHuuBang)...)
	write(out, "data-ownership.json", map[string]any{
		"_": header,
		"_description": "entity -> owning service, from the `-- @entity:` / `-- @scope:` marks in " +
			"each service's migrations (ADR 0021). Rule 2, invariant 1: exactly one owner.",
		"_warnings": canhBaoSoHuu,
		"entities":  soHuuBang,
		"_note_scope": "tenant = per commune · platform = platform-wide · cross-tenant = " +
			"deliberately readable across communes, see rule 1",
	})
	// event-flows LÀ SINH RA TỪ 2026-09-21 — trước đó nó mang nhãn GENERATED mà chưa bao giờ
	// được sinh: `ensurePlaceholder` chỉ ghi một tệp rỗng, rồi RETURN NGAY khi tệp đã có nội
	// dung. Mà `kb/INDEX.yaml` lại định tuyến thẳng câu "đổi cái này thì ai vỡ" vào đó, nên câu
	// trả lời người đọc nhận được là "không ai nghe" — câu sai nguy hiểm nhất tệp này có thể
	// đưa ra, và là câu luôn xanh. Xem tools/kb/sukien.go.
	suKien, canhBaoSuKien, err := quetSuKien(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}
	mucSuKien := map[string]any{
		"_": header,
		"_description": "sự kiện -> bên phát, bên nhận, lược đồ, phiên bản. Tên và lược đồ SINH TỪ " +
			"proto/ (luật 2 bất biến 7); bên phát và bên nhận SINH TỪ mã Go.",
		"_how": "Tên sự kiện: dòng đứng riêng dạng `<miền>.<việc>.v<n>` trong khối chú thích DÍNH LIỀN " +
			"ngay trên `message` của .proto. Bên phát: ĐẶT tên vào phong bì — `events.Envelope{Name: " +
			"...}` — hoặc một lời gọi Publish/Phat mang tên ấy. Bên nhận: SO tên phong bì đang đến " +
			"với nó (`e.Name != TenSuKien...`), một `case \"...\":`, hoặc một lời gọi " +
			"Subscribe/Consume/Nghe. Tên đi qua một hằng số cấp gói vẫn theo được. Hình dạng khác " +
			"thì tên vẫn hiện ở `unclassified_mentions` kèm cảnh báo — không bị bỏ đi trong im lặng.",
		"_warnings": rongNeuNilChuoi(canhBaoSuKien),
		"events":    suKien,
	}
	if len(suKien) == 0 {
		mucSuKien["_empty"] = "không tệp .proto nào khai tên sự kiện"
	}
	write(out, "event-flows.json", mucSuKien)
	ensurePlaceholder(out, "dependencies.json",
		"call graph between services; used to detect synchronous dependency cycles.",
		"no inter-service calls yet")

	stampIndex(root)

	fmt.Printf("kb: %d services, %d exported symbols\n", len(services), len(symbols))
	fmt.Printf("kb: generated at %s\n", time.Now().Format(time.RFC3339))
}

// stampIndex fills the three metadata fields in kb/INDEX.yaml that the file itself declares
// as "`make kb` điền".
//
// WHY: until 2026-09-16 nothing wrote them, so generated_at / from_commit / in_use stayed
// null forever while the file claimed they were maintained. A file that documents its own
// freshness and is never actually stamped is worse than one that says nothing — it invites
// trust it has not earned.
//
// Only these three lines are rewritten; the rest of INDEX.yaml is hand-curated.
func stampIndex(root string) {
	path := filepath.Join(root, "kb", "INDEX.yaml")
	raw, err := os.ReadFile(path)
	if err != nil {
		return
	}

	commit := "unknown"
	if b, err := exec.Command("git", "-C", root, "rev-parse", "--short", "HEAD").Output(); err == nil {
		commit = strings.TrimSpace(string(b))
	}
	used := alwaysLoadTokens(root, string(raw))

	repl := map[string]string{
		"generated_at:": fmt.Sprintf("generated_at: %s", time.Now().UTC().Format(time.RFC3339)),
		"from_commit:":  fmt.Sprintf("from_commit: %s", commit),
		"in_use:":       fmt.Sprintf("  in_use: %d", used),
	}

	lines := strings.Split(string(raw), "\n")
	for i, ln := range lines {
		t := strings.TrimSpace(ln)
		for k, v := range repl {
			if strings.HasPrefix(t, k) {
				// keep any trailing comment on the line
				if idx := strings.Index(ln, "#"); idx >= 0 {
					v += "   " + strings.TrimSpace(ln[idx:])
				}
				lines[i] = v
			}
		}
	}
	_ = os.WriteFile(path, []byte(strings.Join(lines, "\n")), 0o644)
}

var reAlwaysLoad = regexp.MustCompile(`(?m)^\s+-\s+(kb/\S+)`)

// alwaysLoadTokens estimates the always-loaded budget.
//
// THIS MUST MIRROR tools/check_brain.py INVARIANT 5 EXACTLY. check_brain ENFORCES the ceiling
// and fails the gate; this only writes the number into kb/INDEX.yaml, which is the first file
// every session reads. When the two disagree, the number a reader acts on is the wrong one.
//
// It disagreed until 2026-09-16, in two ways, both understating:
//
//	scope    only the always_load list — leaving out CLAUDE.md and the ten @import-ed rule
//	         files, which are the larger half of what is actually always loaded
//	divisor  4 chars/token, the English rule of thumb, while this brain is written in
//	         Vietnamese with diacritics at ~2.2 (check_brain.py:43)
//
// Together they reported 2870 of 25000 — 11% — when the real figure was 20075, or 80%. A
// reader of INDEX.yaml would have concluded there was room for another twenty thousand tokens.
//
// Two details that look like nits and are not: count RUNES, not bytes, because Python's len()
// counts characters and Vietnamese diacritics are multi-byte in UTF-8; and truncate PER FILE,
// because est_tokens() is applied per file before summing.
func alwaysLoadTokens(root, index string) int {
	total := 0
	add := func(rel string) {
		b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			return // a missing file reads as empty in check_brain too
		}
		total += int(float64(len([]rune(string(b)))) / 2.2)
	}

	add("CLAUDE.md")
	if ents, err := os.ReadDir(filepath.Join(root, ".claude", "rules", "critical")); err == nil {
		for _, e := range ents {
			if strings.HasSuffix(e.Name(), ".md") {
				add(".claude/rules/critical/" + e.Name())
			}
		}
	}
	add("kb/INDEX.yaml")
	for _, m := range reAlwaysLoad.FindAllStringSubmatch(index, -1) {
		add(m[1])
	}
	return total
}

// DẤU HIỆU GỐC KHO LÀ `go.work`, KHÔNG PHẢI `go.mod`.
//
// Từ 2026-09-17 mỗi đơn vị triển khai là một module riêng, nên `go.mod` có ở khắp nơi —
// `tools/go.mod` là cái đầu tiên một hàm đi ngược lên gặp phải, và khi đó nó kết luận `tools/`
// là gốc kho. Không có lỗi nào được báo: bộ sinh chỉ đơn giản không tìm thấy dịch vụ nào, rồi
// công bố một hợp đồng rỗng. `go.work` chỉ có đúng một bản, ở đúng gốc.
func findRoot() (string, error) {
	d, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for i := 0; i < 6; i++ {
		if _, err := os.Stat(filepath.Join(d, "go.work")); err == nil {
			return d, nil
		}
		parent := filepath.Dir(d)
		if parent == d {
			break
		}
		d = parent
	}
	return "", fmt.Errorf("go.work not found — run from inside the repository")
}

func scanServices(root string) ([]serviceEntry, error) {
	dir := root
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []serviceEntry
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		name := e.Name()
		if strings.HasPrefix(name, ".") {
			continue
		}
		// Bố cục phẳng: a service is a TOP-LEVEL directory, sitting beside core/, kb/ and
		// web-admin/. `cmd/server/main.go` is what tells them apart — without this filter the
		// generated index called kb/, docs/ and tools/ services, and the index is the file the
		// next session trusts INSTEAD of reading the tree (rule 9). A wrong index is worse than
		// no index: it is believed.
		main := filepath.Join(dir, name, "cmd", "server", "main.go")
		mainErr := error(nil)
		if _, err := os.Stat(main); err != nil {
			mainErr = err
			if _, err := os.Stat(filepath.Join(dir, name, "internal")); err != nil {
				continue // neither an entrypoint nor service-shaped — not a service
			}
		}
		out = append(out, serviceEntry{
			// Name is the BUSINESS name (`identity`), Path is the directory (`service-identity`).
			// The `service-` prefix marks backend-vs-web for a reader of the tree; it is not part
			// of what the service is called, and an index that conflates the two teaches every
			// reader to strip a prefix.
			Name:    strings.TrimPrefix(name, "service-"),
			Path:    name,
			HasMain: mainErr == nil,
			Summary: readmeSummary(filepath.Join(dir, name, "README.md")),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// readmeSummary lifts the bolded Vietnamese unit name and description from the README, so the
// index carries the same words the humans use without anybody copying them by hand.
func readmeSummary(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "**") && strings.Contains(line, "—") {
			return strings.TrimSpace(strings.ReplaceAll(line, "**", ""))
		}
	}
	return ""
}

func scanSymbols(root string) (map[string]symbolEntry, error) {
	out := map[string]symbolEntry{}
	fset := token.NewFileSet()

	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "node_modules", "vendor", "gen", "kb", ".claude":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, perr := parser.ParseFile(fset, path, nil, 0)
		if perr != nil {
			return nil // a file that does not parse is the compiler's problem, not ours
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)

		for _, decl := range f.Decls {
			switch dd := decl.(type) {
			case *ast.FuncDecl:
				if dd.Name.IsExported() {
					at := fmt.Sprintf("%s:%d", rel, fset.Position(dd.Pos()).Line)
					out[qualify(f.Name.Name, dd.Name.Name)] = symbolEntry{Kind: "func", At: at}
				}
			case *ast.GenDecl:
				for _, spec := range dd.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok || !ts.Name.IsExported() {
						continue
					}
					at := fmt.Sprintf("%s:%d", rel, fset.Position(ts.Pos()).Line)
					out[qualify(f.Name.Name, ts.Name.Name)] = symbolEntry{Kind: "type", At: at}
				}
			}
		}
		return nil
	})
	return out, err
}

func qualify(pkg, name string) string { return pkg + "." + name }

func write(dir, name string, v any) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(dir, name), append(b, '\n'), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "kb:", err)
		os.Exit(1)
	}
}

// ensurePlaceholder writes an honest empty index, and never overwrites one that already has
// real content — the hand-curated transaction-boundaries index in particular must survive.
func ensurePlaceholder(dir, name, desc, empty string) {
	path := filepath.Join(dir, name)
	if b, err := os.ReadFile(path); err == nil && !strings.Contains(string(b), "_empty") {
		return
	}
	write(dir, name, map[string]any{
		"_":            header,
		"_description": desc,
		"_empty":       empty,
	})
}
