// Command kb generates the T2/T3 tiers of kb/ from the source code.
//
// WHY THIS EXISTS: hand-written documentation answering "where is X" and "who owns X" is
// wrong by the next day. Measured on the previous system: 38% of file paths cited in the docs
// pointed at files that no longer existed, and the hand-maintained technical-debt table said
// a helper lived in 3 places when it lived in 10.
//
// So those questions are answered by generation, and hand-written prose is reserved for the
// one question no tool can answer: WHY. See rule 9.
//
// Output is deliberately deterministic (sorted everywhere) so that regenerating produces no
// diff when nothing changed.
package main

